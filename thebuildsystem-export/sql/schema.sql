-- One row per client, linked 1:1 to the built-in auth.users table.
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text,
  plan text,                -- e.g. 'solo', 'coaching_6mo', 'coaching_12mo'
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;

-- Each signed-in client can see and edit only their own row.
create policy "Users can view their own profile"
  on public.profiles for select
  using ( auth.uid() = id );

create policy "Users can update their own profile"
  on public.profiles for update
  using ( auth.uid() = id );

-- Automatically create a profile row whenever someone signs up.
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, new.raw_user_meta_data->>'full_name');
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Public nutrition-application submissions (#nutrition-apply on index.html).
-- No login required to submit; only readable from the Supabase dashboard.
create table if not exists public.nutrition_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null,
  sport text not null,
  timeline text not null,
  created_at timestamptz default now()
);

alter table public.nutrition_applications enable row level security;

create policy "Anyone can submit a nutrition application"
  on public.nutrition_applications for insert
  to anon
  with check ( true );

-- Client reviews/testimonials (unlisted review.html submission page +
-- #reviews section on index.html). Anyone with the review.html link can
-- submit, but a submission only becomes publicly visible after Tomi
-- approves it from the Supabase dashboard (flip `approved` to true).
-- The insert policy's WITH CHECK forces approved=false on every new row,
-- so a submitter can never self-approve their own review from the client.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  rating smallint not null check (rating between 1 and 5),
  review_text text not null,
  approved boolean not null default false,
  created_at timestamptz default now()
);

alter table public.reviews enable row level security;

create policy "Anyone can submit a review (pending approval)"
  on public.reviews for insert
  to anon
  with check ( approved = false );

create policy "Anyone can read approved reviews"
  on public.reviews for select
  to anon
  using ( approved = true );

-- "Botón de arrepentimiento" revocation requests (arrepentimiento.html),
-- required by Resolución 424/2020 (Secretaría de Comercio Interior) for
-- any site that sells goods/services online. No login required to submit.
-- A confirmation_code is generated client-side at submission time and
-- shown to the consumer immediately (satisfies the 24-hour, same-channel
-- acknowledgment requirement) — it's stored here too so Tomi can look a
-- request up if someone emails/calls him with just the code.
create table if not exists public.revocation_requests (
  id bigint generated by default as identity primary key,
  confirmation_code text not null,
  full_name text not null,
  email text not null,
  phone text,
  order_reference text,       -- what they bought/contracted (free text, optional)
  reason text,                -- optional — the law does not require a reason
  status text not null default 'pending', -- Tomi can update to 'processed' from the table editor
  created_at timestamptz default now()
);

alter table public.revocation_requests enable row level security;

create policy "Anyone can submit a revocation request"
  on public.revocation_requests for insert
  to anon
  with check ( status = 'pending' );
